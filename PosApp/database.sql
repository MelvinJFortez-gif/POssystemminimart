CREATE DATABASE IF NOT EXISTS pos_db CHARACTER SET utf8mb4;
USE pos_db;
CREATE TABLE IF NOT EXISTS users(
  id INT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(50) UNIQUE NOT NULL,
  password_hash VARCHAR(200) NOT NULL, role ENUM('admin','cashier') NOT NULL DEFAULT 'cashier');
CREATE TABLE IF NOT EXISTS products(
  id INT AUTO_INCREMENT PRIMARY KEY, barcode VARCHAR(64) UNIQUE NOT NULL, name VARCHAR(150) NOT NULL,
  price DECIMAL(10,2) NOT NULL, stock INT NOT NULL DEFAULT 0, category VARCHAR(50) NOT NULL DEFAULT 'General', INDEX(name));
CREATE TABLE IF NOT EXISTS sales(
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, total DECIMAL(10,2) NOT NULL,
  paid DECIMAL(10,2) NOT NULL, change_due DECIMAL(10,2) NOT NULL, method VARCHAR(10) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id));
CREATE TABLE IF NOT EXISTS sale_items(
  id INT AUTO_INCREMENT PRIMARY KEY, sale_id INT NOT NULL, product_id INT NOT NULL,
  qty INT NOT NULL, price DECIMAL(10,2) NOT NULL,
  FOREIGN KEY(sale_id) REFERENCES sales(id), FOREIGN KEY(product_id) REFERENCES products(id));
